-- =====================================================================
-- ปรับตาราง ครั้งที่ 1 (7 พ.ย. 2569): ปุ่มลบในหลังบ้าน + เตรียมระดับสมาชิก (ขั้น 4)
--
-- วิธีใช้: Supabase → SQL Editor → New query → วางทั้งไฟล์ → Run
--   รันซ้ำได้ ไม่เสียหาย (ทุกคำสั่งเช็กก่อนว่ามีแล้วหรือยัง) / ไม่ลบหรือแก้ข้อมูลเดิม
--   ใช้กับทั้งโปรเจคทดลองและโปรเจคใช้จริง (ต่อจาก 001_schema.sql)
-- =====================================================================

begin;

-- ---------------------------------------------------------------------
-- ลบของรางวัล / โปรโมชัน / แต้มพิเศษ จากหลังบ้าน (ผู้ใช้ขอ 7 พ.ย. 2569)
-- "ลบ" = จดเวลาที่ลบไว้ แล้วซ่อนจากทุกหน้า แต่แถวยังอยู่ เพราะ
--   • คูปองที่ลูกค้าแลกไปแล้วอ้างถึงของรางวัล (ต้องใช้ที่ร้านได้ต่อ)
--   • ประวัติแต้มอ้างถึงรหัสกติกาแต้มพิเศษ
--   • รหัสของรายการที่ลบต้องไม่ถูกเอากลับมาใช้กับรายการใหม่ (ประวัติเก่าจะสับสน)
-- ---------------------------------------------------------------------
alter table rewards     add column if not exists deleted_at timestamptz;
alter table promotions  add column if not exists deleted_at timestamptz;
alter table point_rules add column if not exists deleted_at timestamptz;

-- ---------------------------------------------------------------------
-- ระดับสมาชิก: ระบบตรวจลดระดับให้สมาชิกที่ครบกำหนด (tier_until) → ค้นเฉพาะคนที่ถึงกำหนด ไม่ไล่ทั้งร้าน
-- ---------------------------------------------------------------------
create index if not exists members_tier_until_idx on members (shop_id, tier_until) where tier_id is not null;

commit;

-- ผลที่ควรเห็น: ตารางด้านล่างมี 3 แถว (deleted_at ของ 3 ตาราง)
select table_name, column_name from information_schema.columns
where table_schema = 'public' and column_name = 'deleted_at' order by table_name;
